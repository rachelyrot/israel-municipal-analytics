# Build name->id map from DB
all_munis = {m.name: m for m in db.query(Municipality).all()}

# Which have 2016 data
munis_with_2016 = set(
    row[0] for row in
    db.query(Municipality.name)
    .join(DataPoint, Municipality.id == DataPoint.municipality_id)
    .filter(DataPoint.year == 2016)
    .distinct()
    .all()
)

missing_2016 = []   # in user list, no 2016 data
extra_2016   = []   # have 2016 data, not in user list

for name in user_list:
    if name not in munis_with_2016:
        m = all_munis.get(name)
        missing_2016.append((name, m.id if m else None))

for name in munis_with_2016:
    if name not in set(user_list):
        m = all_munis[name]
        dp_count = db.query(func.count(DataPoint.id)).filter(
            DataPoint.municipality_id == m.id, DataPoint.year == 2016
        ).scalar()
        extra_2016.append((name, m.id, dp_count))

with open('coverage_2016.txt', 'w', encoding='utf-8') as f:
    f.write(f'=== ברשימה אך ללא נתוני 2016 ({len(missing_2016)}) ===\n')
    for name, mid in missing_2016:
        f.write(f'  - {name} (id={mid})\n')
    f.write(f'\n=== יש נתוני 2016 אך לא ברשימה ({len(extra_2016)}) ===\n')
    for name, mid, dp in sorted(extra_2016):
        f.write(f'  + {name} (id={mid}, dp_2016={dp})\n')


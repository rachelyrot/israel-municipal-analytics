all_munis = {m.name: m for m in db.query(Municipality).all()}

munis_with_2015 = set(
    row[0] for row in
    db.query(Municipality.name)
    .join(DataPoint, Municipality.id == DataPoint.municipality_id)
    .filter(DataPoint.year == 2015)
    .distinct().all()
)

user_set = set(user_list_2015)

not_in_db   = [n for n in user_list_2015 if n not in all_munis]
in_db_no_2015 = [n for n in user_list_2015 if n in all_munis and n not in munis_with_2015]
extra_2015  = [(n, db.query(func.count(DataPoint.id)).filter(
                    DataPoint.municipality_id == all_munis[n].id,
                    DataPoint.year == 2015).scalar())
               for n in munis_with_2015 if n not in user_set]

with open('diff_2015.txt', 'w', encoding='utf-8') as f:
    f.write(f'ברשימה: {len(user_list_2015)} | בDB: {len(all_munis)} | עם נתוני 2015: {len(munis_with_2015)}\n\n')

    f.write(f'=== לא קיים בDB בכלל ({len(not_in_db)}) ===\n')
    for n in not_in_db:
        f.write(f'  - {n}\n')

    f.write(f'\n=== קיים בDB אך אין נתוני 2015 ({len(in_db_no_2015)}) ===\n')
    for n in in_db_no_2015:
        m = all_munis[n]
        years = db.query(DataPoint.year.distinct()).filter(DataPoint.municipality_id == m.id).order_by(DataPoint.year).all()
        f.write(f'  - {n} (id={m.id}, שנים={[y[0] for y in years]})\n')

    f.write(f'\n=== יש נתוני 2015 אך לא ברשימה ({len(extra_2015)}) ===\n')
    for n, dp in sorted(extra_2015):
        f.write(f'  + {n} (dp_2015={dp})\n')

